"""Human-readable description of a research dataset: what is in it, how good it
is, who was tradable when. Price-based findings come from the development
period only; for the sealed test period only structure (dates, row counts) is
shown, taken from the manifest."""

from __future__ import annotations

from typing import Any

import pandas as pd

from qts.market_data.quality import SymbolQuality, audit_universe, compare_with_live, summarise
from qts.market_data.universe import membership
from qts.research.dataset import SealedDataset


def describe(dataset: SealedDataset, live_check: list[str] | None = None) -> dict[str, Any]:
    spec = dataset.spec
    ids = dataset.verify()
    development = dataset.development()
    split_eve = spec.split - pd.Timedelta(days=1)
    audits = audit_universe(development, spec.timeframe, split_eve)
    table = membership(development, spec.rules)
    size = table.sum(axis=1)
    days = pd.DatetimeIndex(table.index)
    ever = table.any()
    last = {s: f.index[-1] for s, f in development.items()}
    manifest = dataset.build_manifest()["symbols"]
    test_end = pd.Timestamp(spec.test_end, tz="UTC")
    in_test = {s: m["test"] for s, m in manifest.items() if m["test"]}
    live: list[dict[str, Any]] = []
    for symbol in live_check or []:
        frame = development.get(symbol)
        if frame is None:
            continue
        end = frame.index[-1]
        try:
            live.append(
                compare_with_live(frame, symbol, spec.timeframe, end - pd.Timedelta(days=199), end)
            )
        except Exception as exc:  # the comparison is a courtesy: never fail the report on it
            live.append({"symbol": symbol, "error": type(exc).__name__})
    return {
        "spec": spec,
        "ids": ids,
        "openings": dataset.openings(),
        "totals": summarise(audits),
        "audits": audits,
        "universe_size_by_year": size.groupby(days.year).mean().round(1).to_dict(),
        "ever_members": sorted(ever[ever].index),
        "members_delisted": sorted(
            s for s in ever[ever].index if last[s] < split_eve - pd.Timedelta(days=7)
        ),
        "monthly_replacements": float(
            (table[days.day == 1].astype(int).diff().abs().sum(axis=1) / 2).mean()
        ),
        "test": {
            "symbols": len(in_test),
            "candles": sum(m["rows"] for m in in_test.values()),
            "new_listings": sum(1 for s in in_test if not manifest[s]["development"]),
            "ended_before_test_end": sum(
                1
                for m in in_test.values()
                if pd.Timestamp(m["last"]) < test_end - pd.Timedelta(days=7)
            ),
        },
        "live": live,
    }


def _worst(audits: list[SymbolQuality], key: str, limit: int = 8) -> list[SymbolQuality]:
    return sorted((a for a in audits if getattr(a, key)), key=lambda a: -getattr(a, key))[:limit]


def render(report: dict[str, Any]) -> str:
    spec, totals, audits = report["spec"], report["totals"], report["audits"]
    rules = spec.rules
    out = [
        f"# Dataset `{spec.name}`",
        "",
        f"{spec.exchange.capitalize()} spot, quote {spec.quote}, {spec.timeframe} candles, from the "
        "exchange's public archive (every file checksum-verified). Generated by "
        "`qts dataset report`; price-based findings below describe the **development period "
        "only**.",
        "",
        "## Periods",
        "",
        "| Segment | From | To | Content id |",
        "|---|---|---|---|",
        f"| Development (research may use it) | {spec.start} | {spec.development_end} | "
        f"`{report['ids']['development_id']}` |",
        f"| **Sealed test** | {spec.split:%Y-%m-%d} | {spec.test_end} | `{report['ids']['test_id']}` |",
        "",
        f"The test period has been opened **{report['openings']}** time(s). The stored data matches "
        "the committed manifest (every instrument, both segments).",
        "",
        "## What is in it (development period)",
        "",
        f"- **{totals['symbols']} instruments, {totals['candles']:,} candles.** "
        f"**{totals['delisted']}** of them stopped trading before the period ended: they are kept, "
        "so results are not conditioned on survival.",
        "- Excluded by rule, whatever their performance: stablecoins and fiat currencies, leveraged "
        "tokens, wrapped duplicates.",
        "- Listed per year: "
        + ", ".join(f"{y}: {n}" for y, n in totals["listed_by_year"].items())
        + ".",
        "- Stopped trading per year: "
        + (", ".join(f"{y}: {n}" for y, n in totals["delisted_by_year"].items()) or "none")
        + ".",
        "",
        "## Quality findings",
        "",
        "| Finding | Count | How it is handled |",
        "|---|---:|---|",
        f"| Instruments with missing candles | {totals['with_gaps']} ({totals['missing_candles']} candles) | "
        "never filled in; an order waits for the next real candle |",
        f"| Holes longer than a week | {totals['long_gaps']} | the instrument's history restarts "
        f"(`max_gap_days` = {rules.max_gap_days}): a ticker reused for another asset is a new instrument |",
        f"| Candles with no trade / flat candles | {totals['zero_volume_candles']} / {totals['flat_candles']} | "
        "liquidity rule keeps such instruments out |",
        f"| Moves above +200% / below -70% in one candle | {totals['extreme_up']} / {totals['extreme_down']} | "
        "kept: real crashes and listing spikes. The first "
        f"{rules.min_history_days} days after a listing are not tradable |",
        f"| Wicks above 3x the candle body | {totals['wicks']} | kept; stops fill at their level or "
        "at the open, never at a wick |",
        f"| Instruments without traded-value data | {totals['without_liquidity_columns']} | — |",
        "| Duplicated timestamps | 0 | removed on write (the later download wins) |",
        "| Timestamps | — | UTC, aligned to the candle grid (enforced on write) |",
        "",
        "Longest holes:",
        "",
        "| Instrument | Missing candles | Longest hole | First candle | Last candle |",
        "|---|---:|---:|---|---|",
    ]
    out += [
        f"| {a.symbol} | {a.missing} | {a.longest_gap} | {a.first:%Y-%m-%d} | {a.last:%Y-%m-%d} |"
        for a in _worst(audits, "missing")
    ]
    out += [
        "",
        "## Who was tradable when",
        "",
        f"Membership is decided from the past only and reviewed on the first day of each month: at "
        f"least {rules.min_history_days} days of uninterrupted history, median traded value of the "
        f"last {rules.liquidity_window_days} days at least {rules.min_quote_volume:,.0f} {spec.quote}, "
        f"and among those the {rules.top_n} most liquid.",
        "",
        "| Year | Average number of members |",
        "|---|---:|",
    ]
    out += [f"| {year} | {size} |" for year, size in report["universe_size_by_year"].items()]
    out += [
        "",
        f"- {len(report['ever_members'])} instruments were members at some point; on average "
        f"{report['monthly_replacements']:.1f} names are replaced at a monthly review.",
        f"- {len(report['members_delisted'])} of the members later stopped trading: "
        + ", ".join(report["members_delisted"])
        + ".",
        "",
        "## Sealed test period (structure only)",
        "",
        f"{report['test']['symbols']} instruments, {report['test']['candles']:,} candles; "
        f"{report['test']['new_listings']} of them were listed after the split and "
        f"{report['test']['ended_before_test_end']} stop before the period ends. Nothing else about "
        "this period is computed until it is opened.",
    ]
    if report["live"]:
        out += [
            "",
            "## Archive against the exchange's live market-data API",
            "",
            "Backtests use the archive; a running system sees the API. Same candles?",
            "",
            "| Instrument | Candles compared | Only in archive | Only in API | Largest relative difference |",
            "|---|---:|---:|---:|---:|",
        ]
        for row in report["live"]:
            if "error" in row:
                out.append(f"| {row['symbol']} | not available ({row['error']}) | | | |")
            else:
                worst = max(row["max_relative_difference"].values())
                out.append(
                    f"| {row['symbol']} | {row['compared']} | {row['only_in_archive']} | "
                    f"{row['only_in_live']} | {worst:.1e} |"
                )
    return "\n".join(out) + "\n"
